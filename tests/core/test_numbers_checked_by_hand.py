@pytest.mark.parametrize(("text", "value", "unit"), READ_TO_EXACTLY_THIS)
def test_checked_text_that_names_one_number_is_read_to_exactly_that_number(
    text: str, value: str, unit: str | None
) -> None:
    reading = read_number(text)

    assert isinstance(reading, Recognised)
    assert reading.value == Decimal(value)
    assert reading.unit == unit
    has_caution = Caution.POINT_MAY_BE_THOUSANDS_SEPARATOR in reading.cautions
    assert has_caution == (text in READ_WITH_A_CAUTION)


@pytest.mark.parametrize("text", NEVER_RECOGNISED)
def test_checked_text_that_does_not_is_not_recognised(text: str) -> None:
    assert not isinstance(read_number(text), Recognised)


@pytest.mark.parametrize("character", NUMBER_CHARACTERS_TRIED)
def test_number_character_tried_as_a_unit_is_not_recognised_in_any_place(character: str) -> None:
    recognised = [
        place.format(character)
        for place in PLACES_TRIED
        if isinstance(read_number(place.format(character)), Recognised)
    ]

    assert recognised == []


@pytest.mark.parametrize(("allowed", "text", "reading"), READ_WITH_WORDS_FROM_THE_CALLER)
def test_checked_text_with_words_from_the_caller_is_read_to_exactly_this(
    allowed: tuple[str, ...], text: str, reading: Reading
) -> None:
    assert read_number(text, extra_units=allowed) == reading


def test_no_checked_text_is_listed_twice() -> None:
    texts = [text for text, _, _ in READ_TO_EXACTLY_THIS] + NEVER_RECOGNISED

    assert len(texts) == len(set(texts))
    assert len(NUMBER_CHARACTERS_TRIED) == len(set(NUMBER_CHARACTERS_TRIED)) == 51
