# --- where a finding points -------------------------------------------------


def test_finding_names_the_file_the_line_and_the_text() -> None:
    text = f"first line\nsecond line\nroot = {MAC_HOME}/ledger\n"

    (finding,) = scan_text(Path("src/settings.py"), text)

    assert finding.path == Path("src/settings.py")
    assert finding.line == 3
    assert finding.kind is Kind.LOCAL_PATH
    assert str(finding).startswith("src/settings.py:3: machine-specific absolute path")


def test_every_offending_line_is_reported() -> None:
    text = f"{ASSISTANT}\nfine\n{LOG_FILE_STEM}\n{MAC_HOME}/x\n"

    found = [(finding.line, finding.kind) for finding in scan_text(Path("notes.md"), text)]

    assert found == [(1, Kind.TOOL_ATTRIBUTION), (3, Kind.PRIVATE_LOG_ID), (4, Kind.LOCAL_PATH)]


def test_forbidden_text_in_a_file_name_is_reported() -> None:
    (finding,) = scan_text(Path("docs", f"{LOG_FILE_STEM}-plan.md"), "nothing wrong in here")

    assert finding.line == 0
    assert finding.kind is Kind.PRIVATE_LOG_ID
    assert "(file name)" in str(finding)


# --- which files of a repository are scanned --------------------------------


def git(repo: Path, *arguments: str) -> None:
    """Run git in ``repo`` without reading the developer's own git settings."""
    environment = {**os.environ, "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1"}
    subprocess.run(["git", "-C", str(repo), *arguments], check=True, env=environment)


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    git(tmp_path, "init", "--quiet")
    (tmp_path / ".gitignore").write_text("data/\n", encoding="utf-8")
    (tmp_path / "README.md").write_text("A clean file.\n", encoding="utf-8")
    git(tmp_path, "add", ".gitignore", "README.md")
    return tmp_path


def test_clean_repository_has_no_findings(repo: Path) -> None:
    assert scan_repository(repo) == []


def test_tracked_file_is_scanned(repo: Path) -> None:
    (repo / "notes.md").write_text(f"one\n{ASSISTANT} wrote this\n", encoding="utf-8")
    git(repo, "add", "notes.md")

    (finding,) = scan_repository(repo)

    assert (finding.path, finding.line, finding.kind) == (
        Path("notes.md"),
        2,
        Kind.TOOL_ATTRIBUTION,
    )


def test_tracked_file_in_a_subdirectory_is_scanned(repo: Path) -> None:
    (repo / "docs").mkdir()
    (repo / "docs" / "setup.md").write_text(f"cd {MAC_HOME}/ledger\n", encoding="utf-8")
    git(repo, "add", "docs/setup.md")

    (finding,) = scan_repository(repo)

    assert finding.path == Path("docs/setup.md")
    assert finding.kind is Kind.LOCAL_PATH


def test_new_file_git_would_add_is_scanned(repo: Path) -> None:
    (repo / "draft.md").write_text(f"{LOG_FILE_STEM}\n", encoding="utf-8")

    assert kinds(scan_repository(repo)) == {Kind.PRIVATE_LOG_ID}


def test_ignored_file_is_not_scanned(repo: Path) -> None:
    (repo / "data").mkdir()
    (repo / "data" / "cache.txt").write_text(f"{MAC_HOME}/ledger\n", encoding="utf-8")

    assert Path("data/cache.txt") not in listed_files(repo)
    assert scan_repository(repo) == []


def test_tracked_file_with_a_forbidden_name_is_reported(repo: Path) -> None:
    name = f"{LOG_FILE_STEM}-plan.md"
    (repo / name).write_text("nothing wrong in here\n", encoding="utf-8")
    git(repo, "add", name)

    (finding,) = scan_repository(repo)

    assert (finding.path, finding.line) == (Path(name), 0)


def test_file_that_is_not_text_is_skipped_without_failing(repo: Path) -> None:
    (repo / "picture.bin").write_bytes(b"\xff\xfe\x00\x01 not text")
    git(repo, "add", "picture.bin")

    assert Path("picture.bin") in listed_files(repo)
    assert scan_repository(repo) == []


def test_tracked_file_deleted_from_disk_does_not_break_the_scan(repo: Path) -> None:
    (repo / "README.md").unlink()

    assert scan_repository(repo) == []


def test_directory_outside_git_is_refused(tmp_path: Path) -> None:
    with pytest.raises(NotAGitCheckoutError):
        scan_repository(tmp_path)
